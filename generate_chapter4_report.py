heading(doc, "4.11 Discussion in Relation to the Research Objective", 1)
paragraph(
    doc,
    "The principal objective was to use lagged inflation, monetary policy, the exchange rate and the food "
    "index to forecast next-month inflation and determine whether a quantile-derived 80 percent band contains "
    "approximately 80 percent of realised values between 2023 and 2025. Using the present methodology, the "
    "objective is only partially achieved. The code performs the required next-month alignment and produces "
    "three quantile forecasts and a coverage statistic. However, the statistical result is far below the "
    "target and cannot support the conclusion that the interval is reliable."
)
paragraph(
    doc,
    "The finding is nevertheless academically useful because it reveals that nominal uncertainty bands "
    "are not automatically calibrated. Coverage must be tested against realised observations. A nominal "
    "80 percent interval can produce much lower empirical coverage if data quality, structural stability, "
    "predictor measurement or model form are inadequate. Proper interval forecasting therefore requires "
    "formal calibration assessment rather than reliance on the theoretical levels 0.10 and 0.90 (Gneiting "
    "and Raftery, 2007)."
)

heading(doc, "4.12 Statistical and Data Quality Limitations", 1)
paragraph(
    doc,
    "The strongest limitation is the provenance of the working dataset. The compiled dataset is described "
    "as complete because it contains no missing values, but completeness does not establish accuracy. Some "
    "historical monthly inflation, food-index, MPR and exchange-rate observations may be reconstructed, "
    "secondary or subject to inconsistent definitions. If official values are not used, estimated relationships "
    "and coverage figures may reflect compilation decisions rather than the economic process they are intended "
    "to represent."
)
paragraph(
    doc,
    "A second limitation is possible structural change in the macroeconomic environment. Nigeria experienced "
    "large exchange-rate movement and major inflation acceleration in the test horizon. A fixed parameter model "
    "trained before 2023 cannot account fully for policy shifts, rebasing, market redesign or changes in price "
    "formation. A rolling-window design, time-varying coefficients or regime indicators could be more appropriate."
)
paragraph(
    doc,
    "Third, model coefficients may be unstable because inflation, food prices and exchange rates trend together. "
    "Coefficient significance does not resolve multicollinearity and cannot identify causation. Fourth, the "
    "program sorts crossing quantile estimates as a numerical post-processing step. Although this guarantees "
    "order, sorting may not provide a simultaneous constrained distribution and should be distinguished from "
    "the forecasts generated by the original quantile models."
)
paragraph(
    doc,
    "Finally, the evaluation uses a fixed test horizon of 35 months. No out-of-sample uncertainty intervals "
    "for coverage itself are reported and the sample is too small to divide confidently into additional "
    "inflation regimes. Coverage can vary substantially across samples. Bootstrap intervals or block-bootstrap "
    "methods would be appropriate because monthly observations are serially dependent."
)

heading(doc, "4.13 Policy Implications", 1)
paragraph(
    doc,
    "For monetary-policy purposes, the result cautions against presenting the three quantile curves as "
    "precise policy guidance in their present form. The broad interval desired by an MPC committee should "
    "communicate risk without hiding known sources of uncertainty. A nominal 80 percent interval with empirical "
    "coverage of 25.71 percent would provide an inaccurate representation of risk. It could cause decision makers "
    "to place unjustified confidence in a narrowly defined range."
)
paragraph(
    doc,
    "Theoretically, a median forecast of 25 percent accompanied by correctly calibrated quantiles can be "
    "more informative than a point forecast alone. The median forecast communicates the central tendency, "
    "while the outer quantiles communicate downside and upside risk. For Nigeria, this is useful if policy "
    "analysis also distinguishes exchange-rate pass-through, food supply shocks, fiscal pressure and monetary "
    "conditions. Nevertheless, the interval's empirical accuracy should be updated continuously. Ex-post "
    "coverage is necessary to assess whether stated uncertainty matches realised outcomes."
)

